"""Feature 1.9 — AI-generated summaries with a deterministic extractive fallback.

Decision 2 (ai/decisions.md): generative output is always paired with an
auditable extractive fallback, and the UI must label which one produced the text
(docs/ethical-compliance.md §Principle 2: Transparency).
"""
from __future__ import annotations

DANGER_KEYWORDS = [
    "hurt", "danger", "scared", "afraid", "kill", "suicide", "abuse", "threat",
    "beat", "unsafe", "alone", "no one", "help", "hopless", "hopeless",
    "मार", "डर", "धमकी",
    "भीती", "मारतो", "धमकी",
]

SUMMARY_SYSTEM_PROMPT = """SYSTEM: You are Sahaara, an AI assistant for a victim support helpline.
CRITICAL RULES:
1. Do NOT make clinical diagnoses.
2. Use "Indicators" language (observed distress, not diagnosed conditions).
3. Output ONLY valid JSON matching the requested schema. No markdown, no filler.
4. Clearly separate what the person SAID from what you INFER."""

JSON_SCHEMA = """{
  "user_statement": "First-person summary of what the person said, max 3 sentences",
  "distress_level": "LOW | MODERATE | HIGH | CRITICAL",
  "potential_underlying_issue": "Brief, non-diagnostic observation",
  "risk_factors": ["..."],
  "recommended_pathways": ["counselling", "medical", "legal_aid", "protection", "shelter"]
}"""


def extractive_summary(transcript_text: str, danger_keywords: list[str] | None = None) -> str:
    """Deterministic fallback — always available, fully auditable."""
    keywords = [k.lower() for k in (danger_keywords or DANGER_KEYWORDS)]
    sentences = [s.strip() for s in transcript_text.replace("! ", ".\n").replace("? ", ".\n").split(". ") if s.strip()]
    flagged = [s for s in sentences if any(k in s.lower() for k in keywords)]

    if not flagged:
        # fall back to the opening statements so the reviewer always has context
        head = sentences[:2]
        if not head:
            return "No transcript content available for extraction."
        return "Extracted Summary (fallback):\n" + "\n".join(f"- {s}" for s in head)

    return "Extracted Summary (fallback):\n" + "\n".join(f"- {s}" for s in flagged[:6])


def build_summary(
    transcript_text: str,
    flags: list[dict],
    profile: dict,
    llm_result: dict | None = None,
) -> dict:
    """Build the structured summary response (build/Requirement. 109.md schema)."""
    fallback_text = extractive_summary(transcript_text)

    if llm_result and llm_result.get("ok"):
        data = llm_result.get("data") or {}
        return {
            "summary_type": "STRUCTURED",
            "generated_by": "ai",
            "model": llm_result.get("model", "llm"),
            "confidence": round(float(llm_result.get("confidence", 0.9)), 2),
            "label": f"Generated by AI (Confidence: {round(float(llm_result.get('confidence', 0.9)), 2)})",
            "verbatim_summary": {
                "user_statement": data.get("user_statement", "") or "",
                "language": llm_result.get("language", "en"),
            },
            "ai_inference": {
                "distress_level": data.get("distress_level", "UNKNOWN"),
                "potential_underlying_issue": data.get("potential_underlying_issue", ""),
                "risk_factors": data.get("risk_factors", []),
                "recommended_pathways": data.get("recommended_pathways", []),
                "derived_from_flags": [
                    {"indicator": f["category"], "confidence": f["confidence"]} for f in flags
                ],
            },
            "fallback_text": fallback_text,
        }

    # Extractive path (Feature 1.9 fallback + Feature 1.14 human mode)
    distress_level = "UNKNOWN"
    severity_rank = {"low": 0, "medium": 1, "high": 2, "critical": 3}
    best = max((severity_rank.get(f["severity"], 0) for f in flags), default=0)
    distress_level = {0: "UNKNOWN", 1: "MODERATE", 2: "HIGH", 3: "CRITICAL"}[best]

    statement_lines = [s.strip() for s in transcript_text.split("\n") if s.strip()][:3]
    return {
        "summary_type": "EXTRACTIVE_FALLBACK",
        "generated_by": "fallback",
        "model": "extractive-rules-1.4",
        "confidence": 0.55,
        "label": "Extracted Fallback",
        "verbatim_summary": {
            "user_statement": " ".join(statement_lines)[:600],
            "language": "auto",
        },
        "ai_inference": {
            "distress_level": distress_level,
            "potential_underlying_issue": "Extractive fallback cannot infer underlying issues.",
            "risk_factors": sorted({f["category"] for f in flags}),
            "recommended_pathways": _suggest_pathways(flags, profile),
            "derived_from_flags": [
                {"indicator": f["category"], "confidence": f["confidence"]} for f in flags
            ],
        },
        "fallback_text": fallback_text,
    }


def _suggest_pathways(flags: list[dict], profile: dict) -> list[str]:
    """Feature 2.16 — AI suggests, humans confirm (never automatic)."""
    cats = {f["category"] for f in flags}
    out = []
    if "self_harm" in cats or (profile.get("immediate_danger", {}).get("level") in ("HIGH", "CRITICAL")):
        out.append("emergency_support")
    if "trauma" in cats or "distress" in cats:
        out.append("counselling")
    if "immediate_danger" in cats:
        out.extend(["protection", "shelter"])
    if "vulnerability" in cats:
        out.append("welfare")
    return sorted(set(out))
