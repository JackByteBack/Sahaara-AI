def test_human_mode_when_ai_unavailable(client, operator_headers):
    """Feature 1.14 — generative AI unconfigured/unreachable ⇒ graceful fallback result."""
    import asyncio

    from app.ai.llm import generate
    from app.ai.summary import build_summary

    result = asyncio.run(generate("I am scared", {}))
    assert result["ok"] is False
    assert result["reason"] in ("generative_ai_not_configured",) or result["reason"].startswith("provider_error")

    flags = [{"category": "distress", "confidence": 0.7, "severity": "medium"}]
    summary = build_summary("I am scared. Please help me.", flags, {}, llm_result=result)
    assert summary["summary_type"] == "EXTRACTIVE_FALLBACK"
    assert summary["label"] == "Extracted Fallback"
    assert summary["fallback_text"].startswith("Extracted Summary")


