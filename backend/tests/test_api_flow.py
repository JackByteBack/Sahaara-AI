def test_end_to_end_flow(client, operator_headers, admin_headers):
    # 1. Start session with consent (Feature 1.7 / 1.10)
    res = client.post("/api/v1/cases/start", json={"initial_language": "en", "mode": "text", "consent": True},
                      headers=operator_headers)
    assert res.status_code == 200, res.text
    case = res.json()
    case_id = case["id"]
    assert case["consent"]["given"] is True

    # 2. Ingest transcript → analysis produces explainable flags (Features 1.1, 1.5)
    res = client.post(f"/api/v1/cases/{case_id}/segments",
                      params={"speech": None},
                      json={"text": "I am feeling scared and hopeless, no one to help me.",
                            "speaker": "caller", "timestamp": 3.5},
                      headers=operator_headers)
    assert res.status_code == 200, res.text

    res = client.get(f"/api/v1/cases/{case_id}", headers=operator_headers)
    data = res.json()
    assert len(data["ai_flags"]) > 0
    flag = data["ai_flags"][0]
    # explainability requirements: evidence, timestamp, confidence, source
    for key in ("transcript_excerpt", "timestamp", "confidence", "source", "severity", "status"):
        assert key in flag
    assert flag["status"] == "suggested"  # AI suggests, human decides
    assert data["victim_safety_profile"]["psych_distress"]["level"] in ("LOW", "MODERATE", "HIGH", "CRITICAL")
    assert 0.0 <= data["review_priority_score"] <= 1.0

    # 3. Human-in-the-loop: confirm the flag (Feature 1.6)
    res = client.post(f"/api/v1/cases/{case_id}/flags/{flag['id']}/decision",
                      json={"decision": "confirm", "notes": "consistent with call"},
                      headers=operator_headers)
    assert res.status_code == 200
    assert res.json()["flag"]["human_decision"] == "confirm"

    # 4. Summary with explicit provenance label (Feature 1.9 / transparency)
    res = client.post(f"/api/v1/cases/{case_id}/summary", headers=operator_headers)
    assert res.status_code == 200
    summary = res.json()
    assert summary["label"] in ("Extracted Fallback",) or summary["label"].startswith("Generated by AI")
    assert "verbatim_summary" in summary and "ai_inference" in summary

    # 5. Review decision recorded (Feature 1.6)
    res = client.post(f"/api/v1/cases/{case_id}/review",
                      json={"decision": "confirm", "override_ai": False, "notes": "reviewed"},
                      headers=operator_headers)
    assert res.status_code == 200
    assert res.json()["final_decision"]["decision"] == "confirm"

    # 6. Referral must be human-confirmed (Features 1.8 / 2.16)
    res = client.post(f"/api/v1/cases/{case_id}/referrals",
                      json={"referral_type": "counselling", "ai_suggested": True},
                      headers=operator_headers)
    assert res.status_code == 200

    # 7. Close + anonymize (Feature 1.10)
    res = client.post(f"/api/v1/cases/{case_id}/anonymize", json={"extra_names": []}, headers=admin_headers)
    assert res.status_code == 200
    data = client.get(f"/api/v1/cases/{case_id}", headers=operator_headers).json()
    assert data["status"] == "closed"
    assert data["anonymized"] is True

    # 8. Closed cases cannot accept new segments
    res = client.post(f"/api/v1/cases/{case_id}/segments",
                      json={"text": "more text", "speaker": "caller", "timestamp": 9.0},
                      headers=operator_headers)
    assert res.status_code == 400

    # 9. Audit trail captured the journey (Feature 1.13)
    entries = client.get(f"/api/v1/cases/{case_id}/audit", headers=admin_headers).json()["entries"]
    actions = {e["action"] for e in entries}
    assert {"created", "ai_analysis", "case_access", "reviewed", "summary_generated", "deleted"} <= actions


def test_safety_override_case_flags_and_blocks(client, operator_headers):
    res = client.post("/api/v1/cases/start", json={"initial_language": "en", "mode": "voice"},
                      headers=operator_headers)
    case_id = res.json()["id"]

    client.post(f"/api/v1/cases/{case_id}/segments",
                json={"text": "He is here right now with a knife, he is beating me and I am in danger.",
                      "speaker": "caller", "timestamp": 2.0},
                headers=operator_headers)

    data = client.get(f"/api/v1/cases/{case_id}", headers=operator_headers).json()
    assert data["safety_override"] is True
    assert data["review_priority_score"] == 1.0

    danger_flag = next(f for f in data["ai_flags"] if f["category"] == "immediate_danger"
                       and f["severity"] in ("high", "critical"))

    # Dismissing a safety-critical flag while override is active must fail
    res = client.post(f"/api/v1/cases/{case_id}/flags/{danger_flag['id']}/decision",
                      json={"decision": "dismiss"}, headers=operator_headers)
    assert res.status_code == 400

    # Escalation by operator is forbidden (RBAC)
    res = client.post(f"/api/v1/cases/{case_id}/review",
                      json={"decision": "escalate", "notes": "urgent"}, headers=operator_headers)
    assert res.status_code == 403

    # Queue ordering: override case first
    cases = client.get("/api/v1/cases", headers=operator_headers).json()["cases"]
    assert cases[0]["id"] == case_id


